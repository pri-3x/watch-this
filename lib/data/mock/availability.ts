export function platformsFor(
  map: AvailabilityMap,
  titleId: string,
  region: RegionId,
): { platforms: PlatformId[]; known: boolean } {
  const row = map[titleId];
  if (!row || row[region] === undefined) {
    return { platforms: [], known: false };
  }
  return { platforms: row[region] ?? [], known: true };
}
